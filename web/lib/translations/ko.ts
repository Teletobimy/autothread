// Create a type that allows any string values for translations
type DeepStringify<T> = {
  [K in keyof T]: T[K] extends object 
    ? T[K] extends readonly string[] 
      ? string[] 
      : DeepStringify<T[K]>
    : string;
};

export type TranslationKeys = DeepStringify<typeof ko>;
